"""Generate the language-neutral vectors in vectors/ from the reference model (Python standard library only).

    python3 -I model/vectors.py           write vectors/*.tsv
    python3 -I model/vectors.py --check   regenerate into memory and compare with vectors/*.tsv; exit 1 on a difference

Inputs, read only: model/fixtures/brd14-valid.tsv and brd14-invalid.tsv (brd14's frozen vectors, unchanged) and
model/fixtures/kan-ids.txt (a corpus of document ids in the KAN namespace; lines that are not valid brd14 are skipped).
"""

import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ecdid as m  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIX = os.path.join(ROOT, "model", "fixtures")
OUT = os.path.join(ROOT, "vectors")
HEADER = "# generated by model/vectors.py from model/ecdid.py; do not edit\n"


def row(*cells):
    return "\t".join(str(c) for c in cells) + "\n"


def valid_row(b):
    f = m.fields(b)
    return row(m.encode(b), b.hex(), m.code_text(f["system"]), m.code_text(f["kind"]), f["time"], f["writer"],
               f["count"], m.system_class(f["system"]), m.stream_text(b))


def gen_valid(rng):
    ids = []
    ms = 1795271400123
    writer = m.writer_for(ms // 1000, 5)
    ids.append(m.pack(m.code("emq"), m.code("job"), ms, writer, 0))
    ids.append(m.pack(m.code("emq"), m.code("job"), ms, writer, 1))
    for s in ("emq", "kan", "ecd", "fvx", "brd", "a22", "zzz"):
        ids.append(m.system_id(s))
    ids.append(m.pack(m.code("a22"), m.code("aaa"), 0, 0, 0))
    ids.append(m.pack(m.code("zzz"), m.code("zzz"), m.TIME_MAX, m.WRITER_MAX, m.COUNT_LIMIT - 1))
    ids.append(m.pack(m.code("322"), m.code("aaa"), 0, 0, 0))
    ids.append(m.pack(m.code("7zz"), m.code("zzz"), m.TIME_MAX, m.WRITER_MAX, m.COUNT_LIMIT - 1))
    ids.append(m.pack(m.code("3ab"), m.code("run"), 1795271400000, 123456789, 7))
    for _ in range(200):
        system = rng.randrange(1024, 1 << 15)
        kind = (rng.randrange(6, 32) << 10) | (rng.randrange(6, 32) << 5) | rng.randrange(6, 32)
        ids.append(m.pack(system, kind, rng.getrandbits(48), rng.getrandbits(30), rng.getrandbits(18)))
    out = [HEADER, "# the canonical text and the 16 bytes of valid ids, both ways\n",
           "# text\thex\tsystem\tkind\ttime\twriter\tcount\tclass\tstream\n"]
    for b in ids:
        assert m.parse(m.encode(b)) == b
        out.append(valid_row(b))
    return "".join(out)


