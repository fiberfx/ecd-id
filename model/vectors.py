def gen_lease():
    cases = [
        ("worked", "emq:895287301:1795271400000:1795357800000"),
        ("detached", "3ab:123456789:1795271400000:1795357800000"),
        ("one-ms", "kan:0:1:1"),
        ("writer-max", f"kan:{m.WRITER_MAX}:1:2"),
        ("time-max", f"kan:7:{m.TIME_MAX - m.LEASE_TERM_MAX}:{m.TIME_MAX}"),
        ("writer-over", f"kan:{m.WRITER_MAX + 1}:1:2"),
        ("not-before-zero", "emq:5:0:1000"),
        ("reversed", "emq:5:2000:1000"),
        ("term-over", f"emq:5:1000:{1000 + m.LEASE_TERM_MAX + 1}"),
        ("time-over", f"emq:5:{m.TIME_MAX}:{m.TIME_MAX + 1}"),
        ("system-reserved", "2ab:5:1000:2000"),
        ("system-upper", "EMQ:5:1000:2000"),
        ("leading-zero", "emq:05:1000:2000"),
        ("three-parts", "emq:5:1000"),
        ("five-parts", "emq:5:1000:2000:3"),
        ("empty-writer", "emq::1000:2000"),
        ("negative", "emq:-5:1000:2000"),
        ("space", "emq: 5:1000:2000"),
    ]
    out = [HEADER, "# lease texts (system:writer:not_before:not_after) and their strict parse\n",
           "# case\ttext\texpect\n"]
    for name, s in cases:
        try:
            lease = m.parse_lease(s)
            assert m.lease_text(lease) == s
            out.append(row(name, s, "ok"))
        except m.Refused as e:
            out.append(row(name, s, "!" + e.reason))
    out.append("# writer = (grant second mod 2^17) * 2^13 + index\n# second\tindex\twriter\n")
    for second, index in ((1795271400, 5), (0, 0), (131071, 8191), (131072, 0), (1795271400 + 131072, 5),
                          (4102444800, 4096)):
        out.append(row("writer", second, index, m.writer_for(second, index)))
    return "".join(out)


def gen_mint():
    out = [HEADER, "# minter scenarios: each scenario starts with a lease; mint rows give the clock and the kind\n",
           "# burst rows mint N ids at one clock reading and give the last; expect is a text or !reason\n",
           "# scenario\top\tclock\targ\texpect\n"]

    def scenario(name, lease_s, steps):
        mt = m.Minter(m.parse_lease(lease_s))
        out.append(row(name, "lease", "-", lease_s, "ok"))
        for op, clock, arg in steps:
            try:
                if op == "mint":
                    res = m.encode(mt.mint(clock, arg))
                elif op == "burst":
                    kind, n = arg.split("*")
                    for _ in range(int(n)):
                        b = mt.mint(clock, kind)
                    res = m.encode(b)
                elif op == "switch":
                    mt.switch(m.parse_lease(arg))
                    res = "ok"
                else:
                    raise AssertionError(op)
            except m.Refused as e:
                res = "!" + e.reason
            out.append(row(name, op, "-" if clock is None else clock, arg, res))

    T = 1795271400123
    scenario("basic", "emq:895287301:1795271400000:1795357800000",
             [("mint", T, "job"), ("mint", T, "job"), ("mint", T, "evt"), ("mint", T + 1, "job"),
              ("mint", T + 1000, "sto"), ("mint", T + 1000, "dbs")])
    scenario("clock-back", "emq:895287301:1795271400000:1795357800000",
             [("mint", T, "job"), ("mint", T - 500, "job"), ("mint", T - 5000, "evt"), ("mint", T + 2, "job")])
    scenario("slow-clock", "kan:42:1795271400000:1795357800000",
             [("mint", 1700000000000, "doc"), ("mint", 1700000000000, "doc"), ("mint", 1795271400005, "doc")])
    scenario("burst", "emq:7:1795271400000:1795357800000",
             [("burst", T, "evt*262144"), ("mint", T, "evt"), ("mint", T, "evt"), ("mint", T + 1, "evt"),
              ("mint", T + 2, "evt")])
    scenario("lease-ended", "emq:9:1795271400000:1795271401000",
             [("mint", 1795271400999, "job"), ("mint", 1795271401000, "job"), ("mint", 1795271401001, "job"),
              ("mint", 1795271400000, "job")])
    scenario("burst-past-end", "emq:9:1795271400000:1795271400001",
             [("burst", 1795271400001, "job*262144"), ("mint", 1795271400001, "job")])
    scenario("switch-lower", "emq:900000000:1795271400000:1795357800000",
             [("mint", T, "job"), ("mint", T, "job"), ("switch", None, "emq:5:1795271300000:1795357700000"),
              ("mint", T, "job"), ("mint", T + 5, "job")])
    scenario("switch-system", "emq:900000000:1795271400000:1795357800000",
             [("mint", T, "job"), ("switch", None, "kan:5:1795271400000:1795357800000"), ("mint", T, "job")])
    scenario("switch-ended", "emq:900000000:1795271400000:1795357800000",
             [("mint", T, "job"), ("switch", None, f"emq:5:1795271300000:{T}"), ("mint", T, "job")])
    scenario("kind", "emq:1:1795271400000:1795357800000",
             [("mint", T, "j2b"), ("mint", T, "JOB"), ("mint", T, "jo"), ("mint", T, "job")])
    scenario("detached", "3ab:123456789:1795271400000:1795357800000", [("mint", T, "run"), ("mint", T, "run")])
    return "".join(out)


def gen_mxdb():
    out = [HEADER, "# mxdb's 16-byte identities: owner = the system's own id (kind sys, zero local part);\n",
           "# store and database ids are minted ids of kinds sto and dbs; the lineage is not an Ecd ID\n",
           "# field\ttext\thex\texpect\n"]
    for s in ("emq", "kan", "ecd", "fvx", "brd"):
        b = m.system_id(s)
        out.append(row("owner", m.encode(b), b.hex(), "ok"))
    mt = m.Minter(m.parse_lease("emq:895287301:1795271400000:1795357800000"))
    for field, kind in (("store", "sto"), ("database", "dbs"), ("database", "dbs"), ("transaction", "txn")):
        b = mt.mint(1795271400200, kind)
        out.append(row(field, m.encode(b), b.hex(), "ok"))
    for field in ("none", "store", "database"):
        try:
            m.check_binary(bytes(16))
            raise AssertionError("all zero accepted")
        except m.Refused as e:
            out.append(row(field, "-", bytes(16).hex(), "!" + e.reason))
    return "".join(out)


def read_tsv(path):
    with open(path, encoding="utf-8") as fh:
        return [ln.rstrip("\n").split("\t") for ln in fh if ln.strip() and not ln.startswith("#")]


def gen_embed_brd14():
    out = [HEADER, "# brd14's frozen valid vectors and their embedding under the system brd\n", "# brd14\tsnow\ttext\n"]
    for r in read_tsv(os.path.join(FIX, "brd14-valid.tsv")):
        ns, snow, t14 = r[0], int(r[1]), r[2]
        b = m.embed(t14)
        assert m.brd14_decode(t14) == (ns, snow) and m.unembed(b) == t14
        out.append(row(t14, snow, m.encode(b)))
    return "".join(out)


def gen_embed_invalid():
    names = {"LENGTH": "brd14-length", "NAMESPACE": "brd14-namespace", "CHARSET": "brd14-charset",
             "RANGE": "brd14-range"}
    out = [HEADER, "# brd14's frozen invalid vectors: each is refused before embedding, with brd14's own class\n",
           "# input_hex\treason\n"]
    for r in read_tsv(os.path.join(FIX, "brd14-invalid.tsv")):
        raw = b"" if r[0] == "-" else bytes.fromhex(r[0])
        try:
            m.embed(raw)
            raise AssertionError(f"embedded {r[0]}")
        except m.Refused as e:
            assert e.reason == names[r[1]], (r, e.reason)
            out.append(row(r[0], e.reason))
    return "".join(out)


def gen_embed_kan():
    with open(os.path.join(FIX, "kan-ids.txt"), encoding="utf-8") as fh:
        raw = sorted({ln.strip() for ln in fh if ln.strip()})
    kept, skipped = [], 0
    for t14 in raw:
        try:
            kept.append((t14, m.embed(t14)))
        except m.Refused:
            skipped += 1
    texts = [m.encode(b) for _, b in kept]
    assert len(set(texts)) == len(kept)
    assert [b for _, b in sorted(kept)] == sorted(b for _, b in kept)
    folded = {}
    for t14, _ in kept:
        folded.setdefault(t14.lower(), []).append(t14)
    pairs = sum(1 for v in folded.values() if len(v) > 1)
    out = [HEADER, f"# {len(kept)} distinct KAN document ids that decode as valid brd14 ({skipped} skipped),\n",
           f"# of which {pairs} groups differ only by letter case; each with its embedding under brd\n",
           "# brd14\ttext\n"]
    for t14, b in kept:
        out.append(row(t14, m.encode(b)))
    return "".join(out)


def generate():
    rng = random.Random(0xEC0D1D)
    return {
        "valid.tsv": gen_valid(rng),
        "invalid.tsv": gen_invalid(),
        "binary_invalid.tsv": gen_binary_invalid(),
        "stream.tsv": gen_stream(rng),
        "stream_invalid.tsv": gen_stream_invalid(),
        "lease.tsv": gen_lease(),
        "mint.tsv": gen_mint(),
        "mxdb.tsv": gen_mxdb(),
        "embed_brd14.tsv": gen_embed_brd14(),
        "embed_invalid.tsv": gen_embed_invalid(),
        "embed_kan.tsv": gen_embed_kan(),
    }


def main(argv):
    files = generate()
    if "--check" in argv:
        bad = []
        for name, text in files.items():
            path = os.path.join(OUT, name)
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                bad.append(name)
        extra = sorted(set(os.listdir(OUT)) - set(files))
        for name in bad:
            print(f"DIFF {name}")
        for name in extra:
            print(f"EXTRA {name}")
        print(f"checked {len(files)} files: {'ok' if not bad and not extra else 'differs'}")
        return 1 if bad or extra else 0
    os.makedirs(OUT, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(f"wrote {len(files)} files to vectors/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
