def gen_binary_invalid():
    good = m.parse("emq_job_23obzcbapvupu2272222")
    n = int.from_bytes(good, "big")
    cases = [
        ("all-zero", bytes(16)),
        ("reserved-1", (n | (1 << 96)).to_bytes(16, "big")),
        ("reserved-2", (n | (2 << 96)).to_bytes(16, "big")),
        ("system-reserved", (n & ~(0x7FFF << 113)).to_bytes(16, "big")),
        ("kind-digit", ((n & ~(0x7FFF << 98)) | (m.code("j2b") << 98)).to_bytes(16, "big")),
        ("len15", good[:15]),
        ("len17", good + b"\x00"),
        ("ones", b"\xff" * 16),
    ]
    out = [HEADER, "# 16-byte inputs that binary ingress refuses\n", "# case\thex\treason\n"]
    for name, raw in cases:
        try:
            m.check_binary(raw)
            raise AssertionError(f"accepted {name}")
        except m.Refused as e:
            out.append(row(name, raw.hex(), e.reason))
    return "".join(out)


def gen_stream(rng):
    out = [HEADER, "# the stream id of an id, its inverse from the stream's kind, and the 48-bit tail without the system\n",
           "# text\tkind\tstream\tlegacy_tail\n"]
    ids = []
    ms = 1795357800000
    for s in ("emq", "kan", "msi", "man"):
        ids.append(m.pack(m.code(s), m.code("evt"), ms, 3 << 13, 0))
    ids.append(m.pack(m.code("emq"), m.code("evt"), ms, 3 << 13, 1))
    ids.append(m.pack(m.code("zzz"), m.code("zzz"), m.TIME_MAX, m.WRITER_MAX, m.COUNT_LIMIT - 1))
    ids.append(m.pack(m.code("322"), m.code("aaa"), 1, 0, 0))
    for _ in range(50):
        ids.append(m.pack(rng.randrange(1024, 1 << 15), m.code("evt"), rng.getrandbits(48), rng.getrandbits(30),
                          rng.getrandbits(18)))
    for b in ids:
        f = m.fields(b)
        ms_, seq = m.stream_id(b)
        assert seq < 1 << 63
        assert m.from_stream(m.code_text(f["kind"]), ms_, seq) == b
        out.append(row(m.encode(b), m.code_text(f["kind"]), m.stream_text(b), m.legacy_tail(b)))
    return "".join(out)


