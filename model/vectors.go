// mintStep is one step of a minter scenario: op is mint, burst (arg is KIND*N) or switch (arg is a lease).
type mintStep struct {
	op    string
	clock uint64
	arg   string
}

func scenario(out *strings.Builder, name, leaseStr string, steps []mintStep) {
	mt := newMinter(must(parseLease(leaseStr)))
	out.WriteString(row(name, "lease", "-", leaseStr, "ok"))
	for _, s := range steps {
		var res string
		var err error
		switch s.op {
		case "mint":
			var b []byte
			if b, err = mt.mint(s.clock, s.arg); err == nil {
				res = encode(b)
			}
		case "burst":
			kind, n, _ := strings.Cut(s.arg, "*")
			var b []byte
			for i := must(strconv.Atoi(n)); i > 0 && err == nil; i-- {
				b, err = mt.mint(s.clock, kind)
			}
			if err == nil {
				res = encode(b)
			}
		case "switch":
			var l lease
			if l, err = parseLease(s.arg); err == nil {
				err = mt.switchTo(l)
			}
			if err == nil {
				res = "ok"
			}
		default:
			panic("scenario: unknown op " + s.op)
		}
		if err != nil {
			res = "!" + reason(err)
		}
		clock := "-"
		if s.clock != noClock {
			clock = strconv.FormatUint(s.clock, 10)
		}
		out.WriteString(row(name, s.op, clock, s.arg, res))
	}
}

