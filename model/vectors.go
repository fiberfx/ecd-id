func genStream(rng *mersenne) string {
	var out strings.Builder
	out.WriteString(header)
	out.WriteString("# the stream id of an id, its inverse from the stream's kind, and the 48-bit tail without the system\n")
	out.WriteString("# text\tkind\tstream\tlegacy_tail\n")
	var ids [][]byte
	ms := uint64(1795357800000)
	for _, s := range []string{"emq", "kan", "msi", "man"} {
		ids = append(ids, pack(mustCode(s), mustCode("evt"), ms, 3<<13, 0))
	}
	ids = append(ids, pack(mustCode("emq"), mustCode("evt"), ms, 3<<13, 1))
	ids = append(ids, pack(mustCode("zzz"), mustCode("zzz"), timeMax, writerMax, countLimit-1))
	ids = append(ids, pack(mustCode("322"), mustCode("aaa"), 1, 0, 0))
	for i := 0; i < 50; i++ {
		system := rng.randrange(1024, 1<<15)
		time := rng.getrandbits(48)
		writer := rng.getrandbits(30)
		count := rng.getrandbits(18)
		ids = append(ids, pack(system, mustCode("evt"), time, writer, count))
	}
	for _, b := range ids {
		f := fields(b)
		idMS, seq := streamID(b)
		assert(seq < 1<<63, "stream: the sequence is below 2^63")
		assert(bytes.Equal(must(fromStream(codeText(f.kind), idMS, seq)), b), "stream: the inverse returns the id")
		out.WriteString(row(encode(b), codeText(f.kind), streamText(b), legacyTail(b)))
	}
	return out.String()
}

