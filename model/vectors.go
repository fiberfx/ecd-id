func genMxdb() string {
	var out strings.Builder
	out.WriteString(header)
	out.WriteString("# mxdb's 16-byte identities: owner = the system's own id (kind sys, zero local part);\n")
	out.WriteString("# store and database ids are minted ids of kinds sto and dbs; the lineage is not an Ecd ID\n")
	out.WriteString("# field\ttext\thex\texpect\n")
	for _, s := range []string{"emq", "kan", "ecd", "fvx", "brd"} {
		b := must(systemID(s))
		out.WriteString(row("owner", encode(b), hex.EncodeToString(b), "ok"))
	}
	mt := newMinter(must(parseLease("emq:895287301:1795271400000:1795357800000")))
	for _, p := range [][2]string{{"store", "sto"}, {"database", "dbs"}, {"database", "dbs"}, {"transaction", "txn"}} {
		b := must(mt.mint(1795271400200, p[1]))
		out.WriteString(row(p[0], encode(b), hex.EncodeToString(b), "ok"))
	}
	for _, field := range []string{"none", "store", "database"} {
		_, err := checkBinary(make([]byte, 16))
		assert(err != nil, "all zero accepted")
		out.WriteString(row(field, "-", hex.EncodeToString(make([]byte, 16)), "!"+reason(err)))
	}
	return out.String()
}

// generated is one file of vectors/ with its text.
type generated struct{ name, text string }

func generate() []generated {
	rng := newMersenne(0xEC0D1D)
	var files []generated
	add := func(name, text string) { files = append(files, generated{name, text}) }
	add("valid.tsv", genValid(rng))
	add("invalid.tsv", genInvalid())
	add("binary_invalid.tsv", genBinaryInvalid())
	add("stream.tsv", genStream(rng))
	add("stream_invalid.tsv", genStreamInvalid())
	add("lease.tsv", genLease())
	add("mint.tsv", genMint())
	add("mxdb.tsv", genMxdb())
	add("cli.tsv", genCLI())
	return files
}

// check regenerates the vectors in memory and compares them with vectors/*.tsv: it reports each file that differs
// or is missing and each file in vectors/ that the model does not generate, and returns the exit status 1 on any.
func check(files []generated) int {
	bad := false
	known := map[string]bool{}
	for _, f := range files {
		known[f.name] = true
		if got, err := os.ReadFile(filepath.Join(outDir, f.name)); err != nil || string(got) != f.text {
			fmt.Println("DIFF " + f.name)
			bad = true
		}
	}
	entries, err := os.ReadDir(outDir)
	if err != nil {
		fmt.Println("EXTRA " + outDir + ": " + err.Error())
		bad = true
	}
	for _, e := range entries {
		if !known[e.Name()] {
			fmt.Println("EXTRA " + e.Name())
			bad = true
		}
	}
	verdict := "ok"
	if bad {
		verdict = "differs"
	}
	fmt.Printf("checked %d files: %s\n", len(files), verdict)
	if bad {
		return 1
	}
	return 0
}

// run is the command line. Run from the model directory:
//
//	go run .          write vectors/*.tsv
//	go run . --check  regenerate into memory and compare with vectors/*.tsv; exit 1 on a difference
func run(args []string) int {
	if _, err := os.Stat("go.mod"); err != nil || len(args) > 1 || (len(args) == 1 && args[0] != "--check") {
		fmt.Fprintln(os.Stderr, "usage: go run . [--check], from the model directory")
		return 2
	}
	files := generate()
	if len(args) == 1 {
		return check(files)
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		panic(err)
	}
	for _, f := range files {
		if err := os.WriteFile(filepath.Join(outDir, f.name), []byte(f.text), 0o644); err != nil {
			panic(err)
		}
	}
	fmt.Printf("wrote %d files to vectors/\n", len(files))
	return 0
}

func main() { os.Exit(run(os.Args[1:])) }
