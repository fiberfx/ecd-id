// noClock is the clock column of a step that reads no clock.
const noClock = ^uint64(0)

func row(cells ...any) string {
	parts := make([]string, len(cells))
	for i, c := range cells {
		parts[i] = fmt.Sprint(c)
	}
	return strings.Join(parts, "\t") + "\n"
}

// hexOrDash is the hex of raw bytes, with "-" for none.
func hexOrDash(b []byte) string {
	if len(b) == 0 {
		return "-"
	}
	return hex.EncodeToString(b)
}

func dashIfEmpty(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func be16(n *big.Int) []byte { return n.FillBytes(make([]byte, 16)) }

// orShift returns n | v<<shift.
func orShift(n *big.Int, v uint64, shift uint) *big.Int {
	return new(big.Int).Or(n, new(big.Int).Lsh(new(big.Int).SetUint64(v), shift))
}

// clearBits returns n with the bits of mask<<shift cleared.
func clearBits(n *big.Int, mask uint64, shift uint) *big.Int {
	return new(big.Int).AndNot(n, new(big.Int).Lsh(new(big.Int).SetUint64(mask), shift))
}

func validRow(b []byte) string {
	f := fields(b)
	return row(encode(b), hex.EncodeToString(b), codeText(f.system), codeText(f.kind), f.time, f.writer, f.count,
		systemClass(f.system), streamText(b))
}

func genValid(rng *mersenne) string {
	var ids [][]byte
	ms := uint64(1795271400123)
	writer := writerFor(ms/1000, 5)
	ids = append(ids, pack(mustCode("emq"), mustCode("job"), ms, writer, 0))
	ids = append(ids, pack(mustCode("emq"), mustCode("job"), ms, writer, 1))
	for _, s := range []string{"emq", "kan", "ecd", "fvx", "brd", "a22", "zzz"} {
		ids = append(ids, must(systemID(s)))
	}
	ids = append(ids, pack(mustCode("a22"), mustCode("aaa"), 0, 0, 0))
	ids = append(ids, pack(mustCode("zzz"), mustCode("zzz"), timeMax, writerMax, countLimit-1))
	ids = append(ids, pack(mustCode("322"), mustCode("aaa"), 0, 0, 0))
	ids = append(ids, pack(mustCode("7zz"), mustCode("zzz"), timeMax, writerMax, countLimit-1))
	ids = append(ids, pack(mustCode("3ab"), mustCode("run"), 1795271400000, 123456789, 7))
	for i := 0; i < 200; i++ {
		system := rng.randrange(1024, 1<<15)
		k1 := rng.randrange(6, 32)
		k2 := rng.randrange(6, 32)
		k3 := rng.randrange(6, 32)
		kind := k1<<10 | k2<<5 | k3
		time := rng.getrandbits(48)
		writer := rng.getrandbits(30)
		count := rng.getrandbits(18)
		ids = append(ids, pack(system, kind, time, writer, count))
	}
	var out strings.Builder
	out.WriteString(header)
	out.WriteString("# the canonical text and the 16 bytes of valid ids, both ways\n")
	out.WriteString("# text\thex\tsystem\tkind\ttime\twriter\tcount\tclass\tstream\n")
	for _, b := range ids {
		assert(bytes.Equal(must(parse([]byte(encode(b)))), b), "valid: the text parses back")
		out.WriteString(validRow(b))
	}
	return out.String()
}

